#!/usr/bin/env node
/**
 * Design-token generator (no dependencies).
 *
 *   design-system/tokens.json  ──┐   canonical values (ShinaCare "Kohl & Malachite")
 *   design-system/roles.json   ──┴─▶ src/styles/tokens.generated.css   CSS custom properties + t-* type classes
 *                                    src/styles/design-scales.generated.ts   class-name scales for tailwind-merge (cn)
 *
 * Tailwind reads the same two JSON files through design-system/tailwind-preset.ts, so a value changed in
 * tokens.json reaches CSS, utilities and `cn()` without any other edit.
 *
 * Usage: node scripts/build-tokens.mjs [--check]   (--check fails when the generated files are stale)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const tokens = JSON.parse(readFileSync(join(root, 'design-system', 'tokens.json'), 'utf8'));
const roles = JSON.parse(readFileSync(join(root, 'design-system', 'roles.json'), 'utf8'));

const HEADER = `GENERATED by scripts/build-tokens.mjs from design-system/tokens.json + roles.json. Do not edit — run \`npm run tokens\`.`;
const ALIAS = /^\{([a-z0-9-]+)\}$/;
const HEX = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i;

const colorTokens = tokens.color.tokens;
const colorNames = new Set(colorTokens.map((t) => t.name));

/** "#0c6b50" → "12 107 80" (the alpha pair of an 8-digit hex is dropped: Tailwind's <alpha-value> replaces it). */
const toChannels = (hex) => {
  const [, rgb] = hex.match(HEX);
  return [0, 2, 4].map((i) => parseInt(rgb.slice(i, i + 2), 16)).join(' ');
};

const colorLines = [];
for (const { name, value } of colorTokens) {
  const alias = value.match(ALIAS);
  if (alias) {
    if (!colorNames.has(alias[1])) throw new Error(`--${name} aliases unknown token {${alias[1]}}`);
    colorLines.push(`  --${name}: var(--${alias[1]});`, `  --${name}-rgb: var(--${alias[1]}-rgb);`);
  } else if (HEX.test(value)) {
    colorLines.push(`  --${name}: ${value};`, `  --${name}-rgb: ${toChannels(value)};`);
  } else {
    throw new Error(`--${name}: unsupported color value "${value}"`);
  }
}

const roleLines = [];
for (const [role, target] of Object.entries(roles.colorRoles)) {
  if (!colorNames.has(target)) throw new Error(`role "${role}" maps to unknown token "${target}"`);
  if (colorNames.has(role)) throw new Error(`role "${role}" shadows a design token of the same name`);
  roleLines.push(`  --${role}: var(--${target});`, `  --${role}-rgb: var(--${target}-rgb);`);
}

const shadowLines = tokens.shadow.tokens.map(({ name, value }) => `  --${name}: ${value};`);

const flat = (group) => tokens[group].tokens.map(({ name, value }) => `  --${name}: ${value};`);

/** Wrap next/font families as var(--font-x, "Name") so the self-hosted face wins once loaded. */
const fontStack = (stack) =>
  stack
    .split(',')
    .map((part) => {
      const name = part.trim().replace(/^"|"$/g, '');
      return roles.fonts[name] ? `var(${roles.fonts[name]}, "${name}")` : part.trim();
    })
    .join(', ');
const familyLines = Object.entries(tokens.type.families).map(([name, stack]) => `  --font-${name}: ${fontStack(stack)};`);

const typeStyles = tokens.type.groups.flatMap((group) => group.styles.map((style) => ({ ...style, family: group.family })));
const typeClasses = typeStyles.map((s) => {
  const decl = [
    `font-family: var(--font-${s.family})`,
    `font-size: ${s.fontSize}`,
    `line-height: ${s.lineHeight}`,
    `font-weight: ${s.fontWeight}`,
    s.letterSpacing ? `letter-spacing: ${s.letterSpacing}` : null,
  ].filter(Boolean);
  return `.${s.name} { ${decl.join('; ')}; }`;
});

const css = `/* ${HEADER} */

/* Colors: every token is a hex custom property (--malachite) plus its channels (--malachite-rgb) for Tailwind opacity. */
:root,
[data-theme='light'] {
${colorLines.join('\n')}

  /* Semantic roles used by the app's utilities (bg-primary, text-muted-foreground…). */
${roleLines.join('\n')}

${shadowLines.join('\n')}
}

:root {
${flat('spacing').join('\n')}
${flat('radius').join('\n')}
${flat('layout').join('\n')}
${flat('size').join('\n')}
${flat('duration').join('\n')}
${flat('easing').join('\n')}
${flat('zIndex').join('\n')}
${familyLines.join('\n')}
}

/* Type styles (same names as the design system: t-body, t-title…). */
${typeClasses.join('\n')}
`;

const quote = (list) => `[${list.map((n) => `'${n}'`).join(', ')}]`;
const strip = (name, prefix) => name.replace(new RegExp(`^${prefix}`), '');
const aliasNames = (obj) => Object.keys(obj).filter((k) => !k.startsWith('$'));
const scales = `// ${HEADER}
// Class-name scales that tailwind-merge (src/lib/utils.ts) must treat as design-token utilities.

export const fontSizeScale = ${quote([...typeStyles.map((s) => strip(s.name, 't-')), ...aliasNames(roles.textAliases)])};
export const radiusScale = ${quote([...tokens.radius.tokens.map((t) => strip(t.name, 'radius-')).filter((n) => !n.startsWith('arch')).map((n) => roles.radiusNames[n] ?? n), ...aliasNames(roles.radiusAliases).filter((k) => k !== 'DEFAULT')])};
export const shadowScale = ${quote([...tokens.shadow.tokens.filter((t) => !t.name.startsWith('focus-')).map((t) => strip(t.name, 'shadow-')), ...roles.shadowAliases.flat.filter((n) => n !== 'DEFAULT'), ...roles.shadowAliases.float])};
export const durationScale = ${quote([...tokens.duration.tokens.map((t) => strip(t.name, 'dur-')), ...aliasNames(roles.durationAliases)])};
export const easeScale = ${quote([...tokens.easing.tokens.map((t) => strip(t.name, 'ease-')).filter((n) => n !== 'out' && n !== 'in' && n !== 'in-out'), ...aliasNames(roles.easeAliases)])};
export const zScale = ${quote([...tokens.zIndex.tokens.map((t) => strip(t.name, 'z-')), ...aliasNames(roles.zAliases)])};
export const sizeScale = ${quote(tokens.size.tokens.map((t) => t.name))};
`;

const outputs = [
  [join(root, 'src', 'styles', 'tokens.generated.css'), css],
  [join(root, 'src', 'styles', 'design-scales.generated.ts'), scales],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content);
  if (stale.length) {
    console.error(`✗ Generated tokens are stale (${stale.map(([p]) => p.replace(root, '')).join(', ')}). Run \`npm run tokens\`.`);
    process.exit(1);
  }
  console.log('✓ Generated tokens are in sync with design-system/tokens.json');
} else {
  for (const [path, content] of outputs) writeFileSync(path, content);
  console.log(`Generated ${outputs.length} files from design-system/tokens.json (${colorTokens.length} colors, ${typeStyles.length} type styles).`);
}
