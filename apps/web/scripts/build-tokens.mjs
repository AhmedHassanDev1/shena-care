#!/usr/bin/env node
/**
 * SAHEL design-token generator (no dependencies).
 *
 *   design-system/tokens.json      ──┐  canonical SAHEL V2 values (verbatim from docs/design/sahel-v18/03-tokens)
 *   design-system/tokens.app.json  ──┴─▶ src/styles/tokens.generated.css      CSS custom properties
 *                                         src/styles/design-scales.generated.ts  class-name scales for tailwind-merge (cn)
 *
 * Tailwind reads the same two files through design-system/tailwind-preset.ts, so a value changed in either JSON
 * reaches CSS, utilities and `cn()` without any other edit.
 *
 * Usage: node scripts/build-tokens.mjs [--check]   (--check fails when the generated files are stale)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const tokens = JSON.parse(readFileSync(join(root, 'design-system', 'tokens.json'), 'utf8'));
const app = JSON.parse(readFileSync(join(root, 'design-system', 'tokens.app.json'), 'utf8'));

const HEADER = 'GENERATED by scripts/build-tokens.mjs from design-system/tokens.json + tokens.app.json. Do not edit — run `npm run tokens`.';
const HEX = /^#([0-9a-f]{6})$/i;

// tokens.json is canonical: the app file may add names, never redefine one.
const canonicalColors = new Set(tokens.color.tokens.map((t) => t.name));
for (const t of app.color.tokens) {
  if (canonicalColors.has(t.name)) throw new Error(`tokens.app.json redefines canonical color "${t.name}"`);
}
const colorTokens = [...tokens.color.tokens, ...app.color.tokens];

/** "#2236C4" → "34 54 196" so Tailwind can apply /opacity. */
const toChannels = (hex) => {
  const [, rgb] = hex.match(HEX);
  return [0, 2, 4].map((i) => parseInt(rgb.slice(i, i + 2), 16)).join(' ');
};

const colorLines = colorTokens.flatMap(({ name, value }) => {
  if (!HEX.test(value)) throw new Error(`--${name}: unsupported color value "${value}"`);
  return [`  --${name}: ${value};`, `  --${name}-rgb: ${toChannels(value)};`];
});

const lines = (list) => list.map(({ name, value }) => `  --${name}: ${value};`);

// Families are self-hosted under their own names (@fontsource, imported in app/layout.tsx): the stacks are used verbatim.
const familyLines = Object.entries(tokens.type.families).map(([name, stack]) => `  --font-${name}: ${stack};`);

const typeStyles = tokens.type.groups.flatMap((group) => group.styles.map((style) => ({ ...style, family: group.family })));

const css = `/* ${HEADER} */

/* Colors: every token is a hex custom property (--blue) plus its channels (--blue-rgb) for Tailwind opacity. */
:root {
${colorLines.join('\n')}

${lines(tokens.shadow.tokens).join('\n')}
${lines(app.shadow.tokens).map((l) => l.replace('--', '--shadow-')).join('\n')}

${lines(tokens.spacing.tokens).join('\n')}
${lines(tokens.radius.tokens).join('\n')}
${lines(app.size.tokens).join('\n')}

  --ease-standard: ${app.motion.ease.standard};
${Object.entries(app.motion.duration).map(([k, v]) => `  --dur-${k}: ${v};`).join('\n')}
${Object.entries(app.zIndex).filter(([k]) => !k.startsWith('$')).map(([k, v]) => `  --z-${k}: ${v};`).join('\n')}

${familyLines.join('\n')}
}

`;

const quote = (list) => `[${list.map((n) => `'${n}'`).join(', ')}]`;
const scales = `// ${HEADER}
// Class-name scales that tailwind-merge (src/lib/utils.ts) must treat as design-token utilities.

export const fontSizeScale = ${quote([...typeStyles.map((s) => s.name), ...app.fontSize.values])};
export const leadingScale = ${quote(app.lineHeight.values)};
export const radiusScale = ${quote([...tokens.radius.tokens.map((t) => t.name.replace(/^radius-/, '')), ...app.radius.values, 'full', 'none'])};
export const shadowScale = ${quote([...tokens.shadow.tokens.map((t) => t.name), ...app.shadow.tokens.map((t) => t.name), 'none'])};
export const colorScale = ${quote(colorTokens.map((t) => t.name))};
`;

const outputs = [
  [join(root, 'src', 'styles', 'tokens.generated.css'), css],
  [join(root, 'src', 'styles', 'design-scales.generated.ts'), scales],
];

if (process.argv.includes('--check')) {
  const normalize = (s) => s.replace(/\r\n/g, '\n');
  const stale = outputs.filter(([path, content]) => !existsSync(path) || normalize(readFileSync(path, 'utf8')) !== normalize(content));
  if (stale.length) {
    console.error(`✗ Generated tokens are stale (${stale.map(([p]) => p.replace(root, '')).join(', ')}). Run \`npm run tokens\`.`);
    process.exit(1);
  }
  console.log('✓ Generated tokens are in sync with design-system/tokens.json + tokens.app.json');
} else {
  for (const [path, content] of outputs) writeFileSync(path, content);
  console.log(`Generated ${outputs.length} files (${colorTokens.length} colors, ${typeStyles.length} type styles).`);
}
